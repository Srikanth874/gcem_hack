# -*- coding: utf-8 -*-
"""
app.py
======
SolarWatch AI — Flask Gateway for Virtual IoT Sensors (Wokwi ESP32).

Endpoints:
  - POST /sensor  : Ingests real-time simulated telemetry from Wokwi ESP32
  - GET  /sensor  : Serves the latest readings to the SolarWatch AI dashboard
  - GET  /health  : Gateway heartbeat status

Runs locally on: http://127.0.0.1:5000
"""

import time
from datetime import datetime, timezone
from flask import Flask, request, jsonify
from flask_cors import CORS

app = Flask(__name__)

# Allow requests from local frontend (Live Server runs on ports 5500, 3000, 8000)
CORS(app, resources={
    r"/*": {
        "origins": [
            "http://127.0.0.1:5500",
            "http://localhost:5500",
            "http://127.0.0.1:3000",
            "http://localhost:3000",
            "*"
        ]
    }
})

# In-memory storage for the latest sensor telemetry
latest_reading = {
    "data": None,
    "received_at": None,
    "last_updated_epoch": None,
    "packet_count": 0
}

# Required fields and expected types for validation
REQUIRED_FIELDS = {
    "voltage": (int, float),
    "current": (int, float),
    "power": (int, float),
    "irradiance": (int, float),
    "panel_temperature": (int, float),
    "ambient_temperature": (int, float),
    "energy_kwh": (int, float),
    "efficiency": (int, float),
    "shading_level": (int, float),
    "sensor_status": str
}


@app.route("/health", methods=["GET"])
def health_check():
    """Health check endpoint to verify backend status."""
    return jsonify({
        "status": "healthy",
        "service": "SolarWatch AI Gateway",
        "timestamp_utc": datetime.now(timezone.utc).isoformat(),
        "packets_ingested": latest_reading["packet_count"],
        "has_active_sensor": latest_reading["data"] is not None
    }), 200


@app.route("/sensor", methods=["POST"])
def ingest_sensor_data():
    """
    Ingests simulated sensor telemetry from Wokwi ESP32.
    Validates JSON payload, formats timestamps, and stores in memory.
    """
    if not request.is_json:
        return jsonify({
            "error": "Bad Request",
            "message": "Content-Type must be application/json"
        }), 400

    payload = request.get_json(silent=True)
    if not payload:
        return jsonify({
            "error": "Bad Request",
            "message": "Malformed or empty JSON payload"
        }), 400

    # Validate presence and types of required fields
    missing_fields = []
    type_errors = []
    for field, expected_type in REQUIRED_FIELDS.items():
        if field not in payload:
            missing_fields.append(field)
        elif not isinstance(payload[field], expected_type):
            type_errors.append(f"{field} must be {expected_type.__name__}")

    if missing_fields or type_errors:
        return jsonify({
            "error": "Validation Error",
            "missing_fields": missing_fields,
            "type_errors": type_errors
        }), 422

    # Physical plausibility bounds check
    v = float(payload["voltage"])
    i = float(payload["current"])
    p = float(payload["power"])
    irr = float(payload["irradiance"])

    if v < 0 or v > 100 or i < 0 or i > 50 or irr < 0 or irr > 1500:
        return jsonify({
            "error": "Out of Range",
            "message": "Readings exceed simulated physical constraints"
        }), 400

    now_utc = datetime.now(timezone.utc).isoformat()
    now_epoch = time.time()

    # Store formatted telemetry in memory
    latest_reading["data"] = {
        "voltage": round(v, 2),
        "current": round(i, 2),
        "power": round(p, 2),
        "irradiance": round(irr, 1),
        "panel_temperature": round(float(payload["panel_temperature"]), 1),
        "ambient_temperature": round(float(payload["ambient_temperature"]), 1),
        "energy_kwh": round(float(payload["energy_kwh"]), 4),
        "efficiency": round(float(payload["efficiency"]), 1),
        "shading_level": round(float(payload["shading_level"]), 1),
        "sensor_status": str(payload["sensor_status"]),
        "device_timestamp": payload.get("timestamp", now_utc),
        "server_timestamp_utc": now_utc,
        "is_simulated": True,
        "disclaimer": "SIMULATED / VIRTUAL SENSOR DATA -- Statistical model generated by Wokwi ESP32"
    }
    latest_reading["received_at"] = now_utc
    latest_reading["last_updated_epoch"] = now_epoch
    latest_reading["packet_count"] += 1

    return jsonify({
        "success": True,
        "message": "Telemetry received successfully",
        "packet_id": latest_reading["packet_count"],
        "received_at": now_utc
    }), 201


@app.route("/sensor", methods=["GET"])
def get_sensor_data():
    """
    Returns the latest sensor telemetry.
    If no data has been received yet, returns a distinct 'waiting_for_data' status
    instead of presenting dummy zeroes as actual measurements.
    """
    if latest_reading["data"] is None:
        return jsonify({
            "status": "waiting_for_data",
            "message": "Gateway active. No telemetry received from Wokwi ESP32 yet.",
            "is_simulated": True,
            "connected": False
        }), 200

    # Calculate data age in seconds
    age_seconds = round(time.time() - latest_reading["last_updated_epoch"], 1)
    is_stale = age_seconds > 6.0  # Wokwi sends every 2s; >6s means disconnected/stale

    return jsonify({
        "status": "stale" if is_stale else "active",
        "connected": not is_stale,
        "age_seconds": age_seconds,
        "reading": latest_reading["data"],
        "packet_count": latest_reading["packet_count"]
    }), 200


